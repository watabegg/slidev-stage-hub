import { spawn } from 'node:child_process';
import { createHash } from 'node:crypto';
import { readFile, readdir, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import { fileURLToPath } from 'node:url';
import type { Catalog, PlayerDocument } from '@slidock/protocol/contracts';
import { validateCatalog } from '@slidock/protocol/contracts';
import { normalizeHubConfig, HubBuildError, type HubBuildOptions } from './config.js';
import { withBuildWorkspace, promoteBuild } from './artifacts.js';
import { generateThumbnails } from './thumbnail.js';
import { prepareOfflineSite } from './offline.js';

export interface BuildReceipt {
  schemaVersion: 1;
  output: string;
  sourceRoot: string;
  decks: Array<{ id: string; sourcePath: string; revision: string; sourceRevision: string }>;
}
export interface BuildChunk {
  fileName: string;
  modules: string[];
  imports: string[];
  dynamicImports: string[];
  css: string[];
  assets: string[];
  isEntry: boolean;
  isDynamicEntry: boolean;
}
export interface BuildDiagnostics {
  chunkGraph?: BuildChunk[];
  groups: Record<string, BuildChunk[]>;
}
export interface BuildResult {
  output: string;
  catalog: Catalog;
  native: PlayerDocument;
  receipt: BuildReceipt;
  receiptPath: string;
  diagnostics: BuildDiagnostics;
}

function runEngine(jobPath: string, workDir: string): Promise<void> {
  return new Promise((accept, reject) => {
    // Only process-launch essentials are inherited, never ambient Slidev/Vite
    // configuration or NODE_OPTIONS. Presentation input comes from the job file.
    const env: NodeJS.ProcessEnv = {};
    for (const key of ['PATH', 'HOME', 'TMPDIR', 'TEMP', 'TMP', 'SystemRoot', 'WINDIR'])
      if (process.env[key] !== undefined) env[key] = process.env[key];
    const child = spawn(
      process.execPath,
      [fileURLToPath(new URL('./internal/job.mjs', import.meta.url)), jobPath],
      {
        cwd: workDir,
        env,
        stdio: ['ignore', 'pipe', 'pipe'],
      },
    );
    let output = '';
    const append = (bytes: Buffer) => {
      output = (output + bytes.toString()).slice(-16000);
    };
    child.stdout.on('data', append);
    child.stderr.on('data', append);
    child.once('error', (error) =>
      reject(new HubBuildError('BUILD', 'Could not start Hub compiler', { cause: error })),
    );
    child.once('close', (code) =>
      code === 0
        ? accept()
        : reject(new HubBuildError('BUILD', `Hub compiler failed (${code}):\n${output}`)),
    );
  });
}

export async function buildHub(options: HubBuildOptions): Promise<BuildResult> {
  const config = await normalizeHubConfig(options);
  const progress = (phase: string) => options.onProgress?.({ phase });
  return withBuildWorkspace(config.outDir, async (workDir) => {
    try {
      progress('build');
      const jobPath = join(workDir, 'build-job.json');
      await writeFile(jobPath, JSON.stringify({ kind: 'build', ...config, workDir }), {
        mode: 0o600,
      });
      await runEngine(jobPath, workDir);
      const site = join(workDir, 'site');
      const manifestPath = join(site, 'manifest.json');
      // Manifest internals are generated by the isolated Slidev engine. Public
      // wire contracts are validated separately before returning to consumers.
      const manifest = JSON.parse(await readFile(manifestPath, 'utf8')) as {
        decks: Array<{ id: string; revision: string; sourcePath?: string; assets: string[] }>;
        commonAssets: string[];
      };
      const receipt: BuildReceipt = {
        schemaVersion: 1,
        output: config.outDir,
        sourceRoot: config.sourceRoot,
        decks: [],
      };
      for (const deck of manifest.decks) {
        const source = config.decks.find((item) => item.id === deck.id);
        if (!source) throw new HubBuildError('BUILD', `Unknown generated deck ${deck.id}`);
        receipt.decks.push({
          id: deck.id,
          sourcePath: source.entry,
          revision: deck.revision,
          sourceRevision: createHash('sha256')
            .update(await readFile(source.entry))
            .digest('hex'),
        });
        delete deck.sourcePath;
      }
      await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
      await stripNestedSourcePaths(site);
      progress('thumbnails');
      await generateThumbnails({ siteRoot: site, chromiumExecutable: config.chromiumExecutable });
      for (const deck of manifest.decks)
        deck.assets = [...new Set([...deck.assets, `thumbnails/${deck.id}.png`])].sort();
      await writeFile(manifestPath, JSON.stringify(manifest, null, 2) + '\n');
      if (config.offline) {
        progress('offline');
        await prepareOfflineSite({ siteRoot: site, workDir });
      }
      const catalog = validateCatalog(
        JSON.parse(await readFile(join(site, 'catalog.json'), 'utf8')),
      );
      // An all-unsupported static collection is valid for Web-only publication.
      const native = JSON.parse(
        await readFile(join(site, 'native-player.json'), 'utf8'),
      ) as PlayerDocument;
      const receiptFile = join(workDir, 'receipt.json');
      await writeFile(receiptFile, JSON.stringify(receipt, null, 2) + '\n', { mode: 0o600 });
      const diagnostics = await readDiagnostics(workDir);
      progress('promote');
      await promoteBuild(site, receiptFile, config.outDir, workDir);
      return {
        output: config.outDir,
        catalog,
        native,
        receipt,
        receiptPath: `${config.outDir}.receipt.json`,
        diagnostics,
      };
    } catch (error) {
      if (error instanceof HubBuildError) throw error;
      throw new HubBuildError('BUILD', error instanceof Error ? error.message : String(error), {
        cause: error,
      });
    }
  });
}

async function stripNestedSourcePaths(directory: string): Promise<void> {
  for (const entry of await readdir(directory, { withFileTypes: true })) {
    const path = join(directory, entry.name);
    if (entry.isDirectory()) await stripNestedSourcePaths(path);
    else if (entry.name === 'manifest.json') {
      const value = JSON.parse(await readFile(path, 'utf8')) as {
        decks?: Array<{ sourcePath?: string }>;
      };
      for (const deck of value.decks ?? []) delete deck.sourcePath;
      await writeFile(path, JSON.stringify(value, null, 2) + '\n');
    }
  }
}

async function readDiagnostics(workDir: string): Promise<BuildDiagnostics> {
  const result: BuildDiagnostics = { groups: {} };
  for (const entry of await readdir(workDir, { withFileTypes: true })) {
    if (entry.name === 'chunk-graph.json')
      result.chunkGraph = JSON.parse(
        await readFile(join(workDir, entry.name), 'utf8'),
      ) as BuildChunk[];
    if (entry.name === 'groups' && entry.isDirectory()) {
      for (const group of await readdir(join(workDir, 'groups'))) {
        result.groups[group] = JSON.parse(
          await readFile(join(workDir, 'groups', group, 'chunk-graph.json'), 'utf8'),
        ) as BuildChunk[];
      }
    }
  }
  return result;
}
